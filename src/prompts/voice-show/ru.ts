/**
 * Russian two-host show prompt
 * Сценарий для двух азартных радиоведущих, как JSON из реплик. Голоса сохраняют энергичную
 * подачу (HOST_STYLE в voice-show/types.ts); содержание не подаётся как спортивный репортаж.
 *
 * Same content rules as the Hebrew show (./he.ts) and the Russian narrator
 * (../voice-condenser/ru.ts): every event kept, every time in words, weather right
 * after the date, birthday names, the user's own rules. Russian genders past-tense
 * verbs and short adjectives ("готов" / "готова"), so the listener's gender is given
 * and a person of unknown gender gets neutral phrasing, as in Hebrew.
 */

import { sanitizeForPrompt } from '../shared-builders';
import { buildRulesSection } from '../voice-condenser/template';
import { MAX_SOUNDS_PER_SHOW, SOUND_TAGS } from '../../services/voice-show/types';
import type { ShowPerson, ShowPromptContext } from './types';

const SOUND_LIST = SOUND_TAGS.map(sound => `<${sound}>`).join(' ');

// The digests mark built-in calendar reminders with ⏰; only a summary that has one gets this rule.
const REMINDERS_RULE =
  'Напоминания (в сводке они с ⏰) тоже входят, по одной короткой фразе на каждое и никогда не отдельным блоком: дело и время, если оно есть. Напоминание, которое в сводке ещё не сделано, так и называйте (например, "ещё не сделано со вторника"), и никогда не подавайте как одно из событий дня.';

function personLine(label: string, person: ShowPerson): string {
  const name = sanitizeForPrompt(person.name);
  if (person.gender === 'male') return `${label}: ${name} (мужчина — о нём в мужском роде)`;
  if (person.gender === 'female') return `${label}: ${name} (женщина — о ней в женском роде)`;
  return `${label}: ${name} (пол неизвестен — не угадывайте: без "он" и "она", без глаголов прошедшего времени и без кратких прилагательных. Имя всегда в именительном падеже как подлежащее, с глаголом в настоящем времени, у которого нет рода: "${name} забирает детей в час тридцать", "${name} идёт на собеседование")`;
}

function listenerLine(context: ShowPromptContext): string {
  const name = sanitizeForPrompt(context.listener.name);
  return context.listener.gender === 'female'
    ? `Слушательница: ${name}. Женщина — обращайтесь к ней по имени, на "ты" и в женском роде ("ты готова", "ты занята", "не забудь").`
    : `Слушатель: ${name}. Мужчина — обращайтесь к нему по имени, на "ты" и в мужском роде ("ты готов", "ты занят", "не забудь").`;
}

interface KindRules {
  goal: string;
  content: string[];
  length: string;
  /** Turn count asked for in the output line. */
  turns: [min: number, max: number];
}

// The hosts speak about two words a second.
function kindRules(context: ShowPromptContext): KindRules {
  const listener = context.listener.gender === 'female' ? 'слушательницу' : 'слушателя';
  if (context.kind === 'weekly') {
    const weekRef = context.isNextWeek ? 'на следующей неделе' : 'на этой неделе';
    return {
      goal: `что ждёт ${listener} ${weekRef}`,
      content: [
        `Откройте коротким обзором (например, "Вот что тебя ждёт ${weekRef}").`,
        context.culture === 'jewish'
          ? 'Даты называйте так, как они даны в сводке, с еврейской датой, если она есть, но никогда не называйте год, ни еврейский, ни григорианский.'
          : 'Даты называйте так, как они даны в сводке, без года.',
        'Идите день за днём, с относительными днями ("во вторник", "в четверг"), и выделяйте главные события.',
        'Каждое событие из сводки попадает в выпуск, с днём и временем. Несколько событий одного дня можно объединить в одну реплику.',
        'Для семейных событий естественно говорите, чьё это событие.',
        'Неделя без событий: скажите, что календарь свободен. Не придумывайте события.',
      ],
      length: 'около 45-60 секунд речи (примерно 90-125 слов). На насыщенной неделе можно дольше, но никогда за счёт событий.',
      turns: [6, 20],
    };
  }

  // /weather sends the whole forecast text: today and tomorrow, the week, and a 16-day
  // outlook, written around the time it was asked for.
  if (context.kind === 'weather') {
    return {
      goal: 'весь прогноз погоды: сейчас, завтра и ближайшие дни',
      content: [
        'Приветствие: то же, с которого начинается прогноз. Если в нём нет приветствия по времени суток, не придумывайте его.',
        'Только погода: температура, дождь, ветер и качество воздуха, если оно есть в прогнозе.',
        'Сначала сейчас и остаток дня, потом завтра. Если прогноз написан вечером (он начинается с "Добрый вечер" или говорит о вечере и ночи), поменяйте порядок: начните с завтра, а о вечере и ночи хватит одного короткого предложения.',
        'В вечернем прогнозе следующее утро — это "завтра утром", никогда не "сегодня утром": сегодняшнее утро уже прошло. Так же и с другими частями завтрашнего дня ("завтра днём", "завтра вечером").',
        'Неделя: одна-две реплики, только тенденция и заметные перемены. Здесь можно обобщать и группировать дни.',
        'Расширенный прогноз: не больше одного предложения, осторожно ("скорее всего", "ожидается").',
        'В конце один практический совет (зонт, солнцезащитный крем, лишний слой одежды).',
      ],
      length: 'около 35-50 секунд речи (примерно 70-95 слов), 6-10 реплик.',
      turns: [6, 10],
    };
  }

  // The tomorrow summary goes out in the evening; without these rules the Hebrew writer
  // opened with "good morning" and "today" even when the summary said "tomorrow".
  if (context.kind === 'tomorrow') {
    return {
      goal: `что ждёт ${listener} завтра`,
      content: [
        'Приветствие подходит для вечера: то же, с которого начинается сводка (обычно "Добрый вечер"). Никогда не "Доброе утро": если сводка начинается с него, начните с имени без приветствия по времени суток.',
        'Скажите "завтра" уже в первом предложении: это расписание на завтра. Затем завтрашняя дата с днём недели, например "Завтра, в понедельник, ...", без года.',
        'Всё, что в сводке, происходит завтра. Никогда не называйте это "сегодня": не "сегодня понедельник", не "позже сегодня", не "сегодня вечером" и не "этим вечером" о завтрашнем вечере. Говорите "завтра", "завтра утром", "завтра вечером".',
        'Погода на завтра идёт сразу после даты, до расписания: одно-два предложения с практическим советом.',
        'Каждое событие из сводки попадает в выпуск, со временем. Несколько мелких событий можно объединить в одну реплику.',
        'Дети: кратко и естественно (например, "забрать Даню в два").',
        'Взгляд на неделю, если он есть в сводке: кратко, только главные события.',
        'Завтра без событий: скажите, что календарь на завтра свободен, и порадуйтесь этому. Не придумывайте события.',
        'Финал, который подходит для вечера и настраивает на завтра.',
      ],
      length: 'около 45-60 секунд речи (примерно 90-125 слов). В насыщенный день можно дольше, но никогда за счёт событий.',
      turns: [6, 20],
    };
  }

  return {
    goal: `день ${context.listener.gender === 'female' ? 'слушательницы' : 'слушателя'}`,
    content: [
      'Приветствие: то же, с которого начинается сводка ("Доброе утро", "Добрый день" или "Добрый вечер"). Если его нет, не придумывайте приветствие по времени суток.',
      context.culture === 'jewish'
        ? 'Назовите дату с днём недели так, как она дана в сводке, с еврейской датой, если она есть, но никогда не называйте год, ни еврейский, ни григорианский.'
        : 'Назовите дату с днём недели так, как она дана в сводке, без года.',
      'Погода идёт сразу после даты, до расписания: одно-два предложения с практическим советом.',
      'Каждое событие из сводки попадает в выпуск, со временем. Несколько мелких событий можно объединить в одну реплику.',
      'Дети: кратко и естественно (например, "забрать Даню в два").',
      'Взгляд на неделю, если он есть в сводке: кратко, только главные события.',
      'День без событий: скажите, что календарь свободен, и порадуйтесь этому. Не придумывайте события.',
    ],
    length: 'около 45-60 секунд речи (примерно 90-125 слов). В насыщенный день можно дольше, но никогда за счёт событий.',
    turns: [6, 20],
  };
}

export function buildShowPrompt(context: ShowPromptContext): string {
  const female = context.listener.gender === 'female';
  const name = sanitizeForPrompt(context.listener.name);
  const { goal, content, length, turns: [minTurns, maxTurns] } = kindRules(context);

  const family = [listenerLine(context)];
  if (context.spouse) family.push(personLine('Супруг или супруга', context.spouse));
  for (const kid of context.kids) family.push(personLine('Ребёнок', kid));
  if (!context.kids.length && context.hasKidsCalendars) family.push('Есть календари детей.');

  const rules = buildRulesSection(context.globalRules, 'Личные правила пользователя (применить):');

  const allContent = [
    ...content,
    ...(context.summary.includes('⏰') ? [REMINDERS_RULE] : []),
    'Всё время словами, никогда цифрами, по-разговорному в 12-часовом виде с частью суток: "в девять утра", "в десять пятнадцать утра", "в половине пятого дня". Целый час иногда можно подчеркнуть словом "ровно" ("ровно в семь вечера"), но не больше двух раз за выпуск. Не "в девятнадцать ноль-ноль".',
    'Остальные числа тоже словами, например температура ("двадцать восемь градусов").',
    'Дни рождения: возьмите имя человека из события ("день рождения Ивана").',
    'Имена — точно как в сводке: без сокращений и без замены на полную или уменьшительную форму.',
    'Сохраняйте то, что сводка говорит о полуночи: событие "за полночь" заканчивается уже ночью после этого дня, а начавшееся "вчера" не начинается сегодня.',
    'Азарт и шутки не добавляют и не убирают факты: никаких событий, времени, имён или деталей, которых нет в сводке.',
  ];

  return `Вы пишете сценарий короткого аудиовыпуска на русском. Тема: ${goal}. Ведут два азартных ведущих бодрой радиопрограммы.

**Семья:**
${family.join('\n')}
${rules}
**Ведущие:**
- A: главный ведущий. Тёплый, уверенный, под сорок.
- B: молодой ведущий. Энергичный, лет двадцати пяти.
Оба мужчины и говорят о себе в мужском роде. Имён у них нет, не придумывайте.

**Содержание (обязательно):**
${allContent.map((rule, i) => `${i + 1}. ${rule}`).join('\n')}

**Стиль:**
- Энергия радиоэфира: темп, азарт, передачи между ведущими, "Поехали!", "Вот это день!". Это не спортивный репортаж: не подавайте день как матч. Спортивный образ уместен, только если он естественно подходит к тому, о чём речь.
- Лично: уже в начале обратитесь по имени (${name}), а дальше говорите с ${female ? 'ней' : 'ним'} напрямую на "ты", в ${female ? 'женском' : 'мужском'} роде. Не "у вас", а "у тебя".
- Только ${female ? 'слушательница' : 'слушатель'} — это "ты". Ведущие не говорят друг другу "ты", "тебя", "тебе", "твой".
- Короткие реплики: одно-два предложения. Ведущие чередуются и реагируют друг на друга.
- Длина: ${length}
- Короткое начало и короткий энергичный финал.

**Настроение (mood) для каждой реплики, одно из списка:**
- hype: по умолчанию, азарт комментатора
- triumph: праздник (хорошая новость, удачный день)
- suspense: напряжение перед чем-то большим
- amused: весело
- surprised: удивление
- mock_disappointed: шутливое разочарование (дождь, ранний подъём)
- secret: секрет или намёк на сюрприз
- warm: тепло и спокойно (финал, трогательный момент)
Большинство реплик hype. Добавьте 2-4 других настроения там, где это оправдано.

**Звуки:**
- По умолчанию звуков нет: в большинстве выпусков нет ни одного, и это нормально.
- Звук — только реакция на что-то конкретное в тексте: <laugh> или <chuckle> сразу после действительно смешной фразы в той же или в предыдущей реплике, <sigh> — если день и правда тяжёлый, <gasp> — при настоящем сюрпризе, <whispers> — когда ведущий выдаёт секрет или намекает на сюрприз из сводки, <throat-clearing> — прямо перед по-настоящему большой новостью.
- Не ставьте звук просто так, для атмосферы, в нейтральную реплику (обычное событие со временем), а также в первую и последнюю реплики выпуска.
- Только из этого списка: ${SOUND_LIST}
- Не больше ${MAX_SOUNDS_PER_SHOW} на весь выпуск и никогда в двух репликах подряд.
- Никаких других тегов: ни HTML, ни эмодзи, ни markdown, ни ремарок вроде (смеётся) или *вздыхает*.
- Никаких междометий между вертикальными чертами вроде |вау|. Реакция ведущего — это его собственная короткая реплика со словами: звук сам по себе не реплика.
- Не пишите "A:" или "B:" внутри текста.

**Вывод:** только JSON, от ${minTurns} до ${maxTurns} реплик:
{"turns":[{"host":"A","mood":"hype","text":"..."},{"host":"B","mood":"amused","text":"..."}]}

**Исходная сводка (с форматированием — игнорируйте форматирование):**
${context.summary}`;
}
