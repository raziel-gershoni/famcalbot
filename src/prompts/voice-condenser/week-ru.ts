/**
 * Russian Weekly Voice Condenser Prompt
 * Инструкции для Gemini TTS для создания недельной голосовой сводки
 */

import { VoiceCondenserContext } from './types';

export function buildWeeklyVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, globalRules, isNextWeek } = context;

  const weekRef = isNextWeek ? 'на следующей неделе' : 'на этой неделе';

  // Build context section in Russian
  let familyContext = `Имя пользователя: ${userName}.`;
  if (spouseName) {
    familyContext += ` Имя супруга/супруги: ${spouseName}.`;
  }
  if (hasKidsCalendars) {
    familyContext += ` Есть календари детей.`;
  }

  // Build rules section if applicable
  const rulesSection = globalRules?.length
    ? `\n**Пользовательские правила (применить):**\n${globalRules.map((r, i) => `${i + 1}. ${r}`).join('\n')}\n`
    : '';

  return `Прочитай вслух этот недельный обзор календаря естественным, разговорным тоном. Сократи до 30-45 секунд речи на русском языке.

**КОНТЕКСТ:**
${familyContext}
${rulesSection}
**КРИТИЧНО: Должно звучать ЕСТЕСТВЕННО и ПЛАВНО как человеческая речь, не роботизированно. Кратко, но разговорно.**

**ПРАВИЛА:**
1. Начни с обзора недели (например, "Вот что ждёт тебя ${weekRef}")
2. Группируй по дням, но сохраняй разговорность - не перечисляй время роботизированно
3. Выделяй САМЫЕ важные события - не каждую деталь
   - Фокусируйся на встречах, дедлайнах, особых событиях
   - Пропускай рутинные повторяющиеся события, если они не важны
4. Используй относительные ссылки на дни естественно (например, "Во вторник", "В четверг", "В воскресенье")
5. Для семейных событий: упоминай чьё это естественно
   - "У ${spouseName || 'супруга/супруги'}..." или "У детей..."
6. Говори как будто брифуешь кого-то устно - естественный, плавный русский
7. **Полные имена:** Не сокращай имена (например, "Даниил" вместо "Даня")
8. Если несколько событий в один день, объединяй естественно

**Пример НЕПРАВИЛЬНОГО вывода (роботизированный и обрывистый):**
Обзор недели
Понедельник: 09:00 встреча, 14:00 стоматолог
Вторник: Школьное мероприятие детей
Среда: Ничего
Четверг: 10:00 звонок

**Пример ПРАВИЛЬНОГО вывода (естественный и плавный):**
Вот что ждёт тебя на неделе. В понедельник утром встреча и приём у стоматолога в 14:00. Во вторник у детей школьное мероприятие. В четверг звонок в 10:00.

**Оригинальный недельный обзор:**
${summary}

Теперь произнеси сокращённую версию этого недельного обзора:`;
}
