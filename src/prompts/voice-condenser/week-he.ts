/**
 * Hebrew Weekly Voice Condenser Prompt
 * קיצור תצוגה שבועית להאזנה קולית
 */

import { VoiceCondenserContext } from './types';

export function buildWeeklyVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, culture, globalRules } = context;

  // Build context section in Hebrew
  let familyContext = `שם המשתמש: ${userName}.`;
  if (spouseName) {
    familyContext += ` שם בן/בת הזוג: ${spouseName}.`;
  }
  if (hasKidsCalendars) {
    familyContext += ` יש יומנים של ילדים.`;
  }

  // Build rules section if applicable
  const rulesSection = globalRules?.length
    ? `\n**כללים מותאמים אישית (יש ליישם):**\n${globalRules.map((r, i) => `${i + 1}. ${r}`).join('\n')}\n`
    : '';

  // Date format based on culture
  const dateNote = culture === 'jewish'
    ? 'השתמש בתאריכים עבריים (הסר תאריכים לועזיים ושנה עברית)'
    : 'השתמש בתאריכים לועזיים';

  return `אתה מקצר תצוגה שבועית של יומן להאזנה קולית (יעד: 30-45 שניות) בעברית.

**הקשר:**
${familyContext}
${rulesSection}
**קריטי: זה להאזנה קולית - זה חייב להישמע טבעי וזורם כמו דיבור אנושי, לא רובוטי. קצר אבל שיחתי.**

**כללים:**
1. התחל עם סקירת השבוע (לדוגמה: "הנה מה שמחכה לך השבוע" או "מבט לשבוע הבא")
2. ${dateNote}
3. קבץ לפי יום, אבל שמור על שיחתיות - אל תפרט שעות בצורה רובוטית
4. הדגש את האירועים הכי חשובים - לא כל פרט
   - התמקד בפגישות, מועדים, אירועים מיוחדים
   - דלג על אירועים שגרתיים חוזרים אלא אם חשובים
5. השתמש בהתייחסויות יום יחסיות בצורה טבעית (לדוגמה: "ביום שלישי", "ביום חמישי", "בשבת")
6. לאירועי משפחה: ציין של מי בצורה טבעית
   - "ל${spouseName || 'בן/בת הזוג'} יש..." או "לילדים יש..."
7. הסר את כל העיצוב: תגיות HTML, אימוג'ים, כוכביות, מודגש/נטוי
8. כתוב כאילו אתה מתדרך מישהו בעל פה - עברית טבעית וזורמת
9. **שמות מלאים:** אל תקצר שמות (לדוגמה: "דניאל" ולא "דני")
10. **ניקוד:** הוסף ניקוד לשמות פרטיים לדיוק בהקראה

**דוגמה לפלט שגוי (רובוטי וקטוע):**
סקירת השבוע
יום שני: 09:00 פגישה, 14:00 רופא שיניים
יום שלישי: אירוע בית ספר של הילדים
יום רביעי: כלום
יום חמישי: 10:00 שיחה

**דוגמה לפלט נכון (טבעי וזורם):**
הנה מה שמחכה לך השבוע. ביום שני יש לך פגישה בבוקר ורופא שיניים ב-14:00. ביום שלישי לילדים יש אירוע בבית הספר. ביום חמישי יש שיחה ב-10:00.

**הסיכום השבועי המקורי:**
${summary}

**פלט את הגרסה הקולית המקוצרת (טקסט פשוט, דיבור טבעי, בעברית):**`;
}
