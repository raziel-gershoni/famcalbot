/**
 * Hebrew Voice Condenser Prompt
 * קיצור סיכום יומן להאזנה קולית
 */

import { VoiceCondenserContext } from './types';

export function buildVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, culture, globalRules } = context;

  // Build context section in Hebrew
  let familyContext = `שם המשתמש: ${userName}.`;
  if (spouseName) {
    familyContext += ` שם בן/בת הזוג: ${spouseName}.`;
  }
  if (hasKidsCalendars) {
    familyContext += ` יש יומנים של ילדים.`;
  }

  // Build rules section if applicable
  const rulesSection = globalRules?.length
    ? `\n**כללים מותאמים אישית (יש ליישם):**\n${globalRules.map((r, i) => `${i + 1}. ${r}`).join('\n')}\n`
    : '';

  // Date format based on culture
  const dateRule = culture === 'jewish'
    ? '1. השאר רק תאריך עברי עם יום בשבוע (הסר תאריך לועזי, הסר שנה עברית)'
    : '1. השאר תאריך עם יום בשבוע';

  return `אתה מקצר סיכום יומן להאזנה קולית (יעד: 30-45 שניות) בעברית.

**הקשר:**
${familyContext}
${rulesSection}
**קריטי: זה להאזנה קולית - זה חייב להישמע טבעי וזורם כמו דיבור אנושי, לא רובוטי. קצר אבל שיחתי.**

**כללים:**
${dateRule}
2. **חשוב: מזג אוויר מגיע מיד אחרי התאריך, לפני לוח הזמנים**
   - כתוב כמשפטים טבעיים וזורמים (חלקים ושיחתיים, לא קטועים)
   - כלול תנאים, תזמון וטיפ מעשי בצורה טבעית
   - דוגמה: "יהיה גשם אחה״צ, אז קח מטריה" ולא "גשם אחה״צ, מטריה"
3. לפריטים בלוח זמנים: כתוב כמשפטים קצרים אבל טבעיים
   - השתמש במחברים טבעיים וזרימה
   - דוגמה: "יש לך פגישה ב-09:00" ולא "09:00 פגישה"
4. לילדים: השאר קצר אבל טבעי
   - דוגמה: "לאסוף את דני ב-14:00" ולא "14:00 דני"
5. למבט לשבוע (אם קיים): הזכר בקצרה אירועים מרכזיים קרובים
   - דוגמה: "בהמשך השבוע, יש לך תור לרופא שיניים ביום חמישי."
   - כמה שיותר קצר - רק עדכון מהיר
6. הסר את כל העיצוב: תגיות HTML, אימוג'ים, כוכביות, מודגש/נטוי
7. **תוויות סעיפים בעברית:**
   - השתמש בתוויות מינימליות (1-2 מילים) להפרדת סעיפים
   - שמור על הכל טבעי ושיחתי
8. כתוב כאילו אתה מדבר עם מישהו - עברית טבעית, קצרה, זורמת
9. **שמות מלאים:** השאר שמות מלאים - אל תקצר (לדוגמה: "דניאל" ולא "דני", "רחלי" ולא "רח")
10. **ניקוד לטקסט-לדיבור:** הוסף ניקוד לשמות פרטיים ולמילים עם מין דקדוקי לדיוק בהקראה (לדוגמה: רוּת, דָּנִי, הוּא/הִיא)

**דוגמה לפלט שגוי (רובוטי וקטוע):**
יום שני, כ״ח כסלו
מזג אוויר: גשם אחה״צ, מטריה
בשבילך: 09:00 פגישה
איסוף: 14:00 דני

**דוגמה לפלט נכון (טבעי וזורם):**
יום שני, כ״ח כסלו
יהיה גשם אחה״צ, אז כדאי לקחת מטריה.
יש לךָ פגישה ב-09:00.
לאסוף את דָּנִי ב-14:00.
בהמשך השבוע, יש לך תור לרופא שיניים ביום חמישי.

**הסיכום המקורי:**
${summary}

**פלט את הגרסה הקולית המקוצרת (טקסט פשוט, ישיר, בעברית):**`;
}
