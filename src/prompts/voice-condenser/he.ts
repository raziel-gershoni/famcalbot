/**
 * Hebrew Voice Condenser Prompt
 * קיצור סיכום יומן להאזנה קולית
 */

export function buildVoiceCondenserPrompt(fullSummary: string): string {
  return `אתה מקצר סיכום יומן להאזנה קולית (יעד: 30-45 שניות) בעברית.

**קריטי: זה להאזנה קולית - זה חייב להישמע טבעי וזורם כמו דיבור אנושי, לא רובוטי. קצר אבל שיחתי.**

**כללים:**
1. השאר רק תאריך עברי עם יום בשבוע (הסר תאריך לועזי, הסר שנה עברית)
2. **חשוב: מזג אוויר מגיע מיד אחרי התאריך, לפני לוח הזמנים**
   - כתוב כמשפטים טבעיים וזורמים (חלקים ושיחתיים, לא קטועים)
   - כלול תנאים, תזמון וטיפ מעשי בצורה טבעית
   - דוגמה: "יהיה גשם אחה״צ, אז קח מטריה" ולא "גשם אחה״צ, מטריה"
3. לפריטים בלוח זמנים: כתוב כמשפטים קצרים אבל טבעיים
   - השתמש במחברים טבעיים וזרימה
   - דוגמה: "יש לך פגישה ב-09:00" ולא "09:00 פגישה"
4. לילדים: השאר קצר אבל טבעי
   - דוגמה: "לאסוף את דני ב-14:00" ולא "14:00 דני"
5. הסר את כל העיצוב: תגיות HTML, אימוג'ים, כוכביות, מודגש/נטוי
6. **תוויות סעיפים בעברית:**
   - השתמש בתוויות מינימליות (1-2 מילים) להפרדת סעיפים
   - שמור על הכל טבעי ושיחתי
7. כתוב כאילו אתה מדבר עם מישהו - עברית טבעית, קצרה, זורמת

**דוגמה לפלט שגוי (רובוטי וקטוע):**
יום שני, כ״ח כסלו
מזג אוויר: גשם אחה״צ, מטריה
בשבילך: 09:00 פגישה
איסוף: 14:00 דני

**דוגמה לפלט נכון (טבעי וזורם):**
יום שני, כ״ח כסלו
יהיה גשם אחה״צ, אז כדאי לקחת מטריה.
יש לך פגישה ב-09:00.
לאסוף את דני ב-14:00.

**הסיכום המקורי:**
${fullSummary}

**פלט את הגרסה הקולית המקוצרת (טקסט פשוט, ישיר, בעברית):**`;
}
