/**
 * Hebrew Voice Condenser Prompt
 * הוראות דיבור ל-Gemini TTS ליצירת סיכום קולי
 */

import { VoiceCondenserContext } from './types';
import { buildFamilyContext, buildRulesSection } from './template';

export function buildVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, culture, globalRules } = context;

  const familyContext = buildFamilyContext(userName, spouseName, hasKidsCalendars, {
    userName: "שם המשתמש:",
    spouseLabel: "שם בן/בת הזוג:",
    kidsLabel: "יש יומנים של ילדים."
  });

  const rulesSection = buildRulesSection(globalRules, "כללים מותאמים אישית (יש ליישם):");

  // Date format based on culture
  const dateRule = culture === 'jewish'
    ? '1. השאר רק תאריך עברי עם יום בשבוע (הסר תאריך לועזי, הסר שנה עברית)'
    : '1. השאר תאריך עם יום בשבוע';

  return `קרא בקול את סיכום היומן הזה בטון טבעי ושיחתי. קצר ל-30-45 שניות דיבור בעברית.

**הקשר:**
${familyContext}
${rulesSection}
**קריטי: זה חייב להישמע טבעי וזורם כמו דיבור אנושי, לא רובוטי. קצר אבל שיחתי.**

**כללים:**
${dateRule}
2. **חשוב: מזג אוויר מגיע מיד אחרי התאריך, לפני לוח הזמנים**
   - דבר כמשפטים טבעיים וזורמים (חלקים ושיחתיים, לא קטועים)
   - כלול תנאים, תזמון וטיפ מעשי בצורה טבעית
   - דוגמה: "יהיה גשם אחה״צ, אז קח מטריה" ולא "גשם אחה״צ, מטריה"
3. לפריטים בלוח זמנים: דבר כמשפטים קצרים אבל טבעיים
   - השתמש במחברים טבעיים וזרימה
   - דוגמה: "יש לך פגישה ב-09:00" ולא "09:00 פגישה"
4. לילדים: השאר קצר אבל טבעי
   - דוגמה: "לאסוף את דני ב-14:00" ולא "14:00 דני"
5. למבט לשבוע (אם קיים): הזכר בקצרה אירועים מרכזיים קרובים
   - דוגמה: "בהמשך השבוע, יש לך תור לרופא שיניים ביום חמישי."
   - כמה שיותר קצר - רק עדכון מהיר
6. **תוויות סעיפים בעברית:**
   - השתמש בתוויות מינימליות (1-2 מילים) להפרדת סעיפים
   - שמור על הכל טבעי ושיחתי
7. דבר כאילו אתה מדבר עם מישהו - עברית טבעית, קצרה, זורמת
8. **שמות מלאים:** השאר שמות מלאים - אל תקצר (לדוגמה: "דניאל" ולא "דני", "רחלי" ולא "רח")
9. **ניקוד לדיבור:** הוסף ניקוד לשמות פרטיים ולמילים עם מין דקדוקי לדיוק בהגייה (לדוגמה: רוּת, דָּנִי, הוּא/הִיא)
10. **הגיית שמות מותגים:** הגה שמות מותגים באנגלית בצורה טבעית בהקשר עברי (לדוגמה: Zoom כ-"זום", Teams כ-"טימס", Google כ-"גוגל")

**דוגמה לפלט שגוי (רובוטי וקטוע):**
יום שני, כ״ח כסלו
מזג אוויר: גשם אחה״צ, מטריה
בשבילך: 09:00 פגישה
איסוף: 14:00 דני

**דוגמה לפלט נכון (טבעי וזורם):**
יום שני, כ״ח כסלו
יהיה גשם אחה״צ, אז כדאי לקחת מטריה.
יש לךָ פגישה ב-09:00.
לאסוף את דָּנִי ב-14:00.
בהמשך השבוע, יש לך תור לרופא שיניים ביום חמישי.

**הסיכום המקורי:**
${summary}

עכשיו דבר את הגרסה המקוצרת של הסיכום הזה:`;
}
