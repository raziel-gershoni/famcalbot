/**
 * Russian Voice Condenser Prompt
 * Инструкции для Gemini TTS для создания голосовой сводки
 */

import { VoiceCondenserContext } from './types';
import { buildFamilyContext, buildRulesSection } from './template';

export function buildVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, globalRules } = context;

  const familyContext = buildFamilyContext(userName, spouseName, hasKidsCalendars, {
    userName: "Имя пользователя:",
    spouseLabel: "Имя супруга/супруги:",
    kidsLabel: "Есть календари детей."
  });

  const rulesSection = buildRulesSection(globalRules, "Пользовательские правила (применить):");

  return `Ты получишь сводку календаря. Сократи её до 30-45 секунд естественной речи на русском, затем произнеси.

**КОНТЕКСТ:**
${familyContext}
${rulesSection}
**КРИТИЧНО: Должно звучать ЕСТЕСТВЕННО и ПЛАВНО как человеческая речь, не роботизированно. Кратко, но разговорно.**

**ПРАВИЛА:**
1. Оставь ТОЛЬКО дату с днём недели
2. **Читай ВСЕ времена и даты ТОЧНО как написано. Не округляй, не аппроксимируй, не перефразируй.**
3. **Погода: Сократи прогноз до 1-2 естественных предложений. ВСЕГДА включай практический совет (например, "возьми зонт", "оденься теплее"). Погода идёт СРАЗУ после даты, ПЕРЕД расписанием.**
   - Пример: "Днём будет дождь, так что возьми зонт" НЕ "Дождь днём, зонт"
4. Для пунктов расписания: Говори краткими, но естественными предложениями
   - Используй естественные связки и плавность
   - Пример: "У тебя встреча в 09:00" НЕ "09:00 встреча"
5. Для детей: Держи кратко, но естественно
   - Пример: "Забрать Даню в 14:00" НЕ "14:00 Даня"
6. Для обзора недели (если есть): Кратко упомяни ключевые предстоящие события
   - Пример: "На этой неделе у тебя приём у стоматолога в четверг."
   - Как можно короче - быстрое напоминание
7. Говори как будто разговариваешь с кем-то - естественный, краткий, плавный русский
8. **Полные имена:** Оставляй полные имена - не сокращай (например, "Даниил" вместо "Даня")

**Пример НЕПРАВИЛЬНОГО вывода (роботизированный и обрывистый):**
Понедельник, 28 декабря
Погода: Дождь днём, зонт
Для тебя: 09:00 встреча
Забор: 14:00 Даня

**Пример ПРАВИЛЬНОГО вывода (естественный и плавный):**
Понедельник, 28 декабря
Днём будет дождь, так что возьми зонт.
У тебя встреча в 09:00.
Забрать Даню в 14:00.
На этой неделе у тебя приём у стоматолога в четверг.

**Оригинальная сводка:**
${summary}

Теперь произнеси сокращённую версию этой сводки:`;
}
