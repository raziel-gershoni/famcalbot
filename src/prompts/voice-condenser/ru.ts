/**
 * Russian Voice Condenser Prompt
 * Сокращение сводки календаря для голосового прослушивания
 */

import { VoiceCondenserContext } from './types';

export function buildVoiceCondenserPrompt(context: VoiceCondenserContext): string {
  const { summary, userName, spouseName, hasKidsCalendars, globalRules } = context;

  // Build context section in Russian
  let familyContext = `Имя пользователя: ${userName}.`;
  if (spouseName) {
    familyContext += ` Имя супруга/супруги: ${spouseName}.`;
  }
  if (hasKidsCalendars) {
    familyContext += ` Есть календари детей.`;
  }

  // Build rules section if applicable
  const rulesSection = globalRules?.length
    ? `\n**Пользовательские правила (применить):**\n${globalRules.map((r, i) => `${i + 1}. ${r}`).join('\n')}\n`
    : '';

  return `Ты сокращаешь сводку календаря для голосового прослушивания (цель: 30-45 секунд) на русском языке.

**КОНТЕКСТ:**
${familyContext}
${rulesSection}
**КРИТИЧНО: Это для ГОЛОСОВОГО прослушивания - должно звучать ЕСТЕСТВЕННО и ПЛАВНО как человеческая речь, не роботизированно. Кратко, но разговорно.**

**ПРАВИЛА:**
1. Оставь ТОЛЬКО дату с днём недели
2. **ВАЖНО: Погода идёт СРАЗУ после даты, ПЕРЕД расписанием**
   - Пиши естественными, плавными предложениями (гладко и разговорно, НЕ обрывисто)
   - Включай условия, время и практический совет естественно
   - Пример: "Днём будет дождь, так что возьми зонт" НЕ "Дождь днём, зонт"
3. Для пунктов расписания: Пиши краткими, но естественными предложениями
   - Используй естественные связки и плавность
   - Пример: "У тебя встреча в 09:00" НЕ "09:00 встреча"
4. Для детей: Держи кратко, но естественно
   - Пример: "Забрать Даню в 14:00" НЕ "14:00 Даня"
5. Для обзора недели (если есть): Кратко упомяни ключевые предстоящие события
   - Пример: "На этой неделе у тебя приём у стоматолога в четверг."
   - Как можно короче - быстрое напоминание
6. Убери ВСЁ форматирование: HTML-теги, эмодзи, звёздочки, жирный/курсив
7. **Названия разделов на русском:**
   - Используй минимальные названия (1-2 слова) для разделения секций
   - Держи всё естественным и разговорным
8. Пиши как будто говоришь с кем-то - естественный, краткий, плавный русский
9. **Полные имена:** Оставляй полные имена - не сокращай (например, "Даниил" вместо "Даня")

**Пример НЕПРАВИЛЬНОГО вывода (роботизированный и обрывистый):**
Понедельник, 28 декабря
Погода: Дождь днём, зонт
Для тебя: 09:00 встреча
Забор: 14:00 Даня

**Пример ПРАВИЛЬНОГО вывода (естественный и плавный):**
Понедельник, 28 декабря
Днём будет дождь, так что возьми зонт.
У тебя встреча в 09:00.
Забрать Даню в 14:00.
На этой неделе у тебя приём у стоматолога в четверг.

**Оригинальная сводка:**
${summary}

**Выведи ультракраткую голосовую версию (простой текст, прямо, на русском):**`;
}
